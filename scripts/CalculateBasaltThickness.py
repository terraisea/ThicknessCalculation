# Basalt transition rule used in this version.
# - Basalt is CF > 8.2.
# - For a basalt rim, the lower boundary is represented by the first inward
#   non-basalt pixel center (CF <= 8.2), not by the previous basalt pixel.
# - For a non-basalt rim, the upper boundary is the first inward basalt pixel
#   center (CF > 8.2), and the lower boundary is the next inward non-basalt
#   pixel center (CF <= 8.2). A single basalt pixel is still accepted.
# This constant is kept only for backward-compatible diagnostic columns.
MAX_CONSECUTIVE_NONBASALT_GAP = 2
MIN_BASALT_PIXELS_FOR_THICKNESS = 1

# Crater-level aggregation thresholds.
# These two values come from the MATLAB IQR upper-fence statistics:
#   relative_spread_threshold = Q3 + 1.5 * IQR = 3.442
#   rel_dev_threshold         = Q3 + 1.5 * IQR = 2.011
# relative_spread is only a trigger for direction-level outlier checking;
# it does NOT remove the whole crater.
# rel_dev is used to identify direction-level outliers.
RELATIVE_SPREAD_THRESHOLD = 3.442
REL_DEV_THRESHOLD = 2.011

# Data-driven thresholds used by the sequential low-tail aggregation rule.
# These values were derived from the current Thickness.csv / crater-summary
# direction-thickness distribution:
#   n == 2:
#       pair_ratio = min(T1,T2) / max(T1,T2)
#       Otsu automatic threshold = 0.496
#   n >= 3:
#       low_ratio = min_value / median(other directions)
#       Otsu automatic threshold = 0.477
#
# The sequential low-tail rule uses PAIR_RATIO_THRESHOLD and LOW_RATIO_THRESHOLD.
# HIGH_PAIR_DIFF_THRESHOLD is kept only for backward compatibility with older
# function signatures/comments; the revised sequential rule does not require
# the two high values to be close before removing a clearly low-tail value.
PAIR_RATIO_THRESHOLD = 0.496
LOW_RATIO_THRESHOLD = 0.477
HIGH_PAIR_DIFF_THRESHOLD = 0.569

