def direction_field_name(profile_type: str, side: str) -> Optional[str]:
    """
    Map the four direction records to original direction fields in the crater-level output.

    row-left  -> row_left
    row-right -> row_right
    col-left  -> col_left
    col-right -> col_right

    Hyphens are avoided because shapefile field names should use underscores.
    """
    p = str(profile_type).lower()
    s = str(side).lower()
    if p == "row" and s == "left":
        return "row_left"
    if p == "row" and s == "right":
        return "row_right"
    if p == "col" and s == "left":
        return "col_left"
    if p == "col" and s == "right":
        return "col_right"
    return None


def aggregate_crater_thickness_values(values,
                                      spread_threshold=RELATIVE_SPREAD_THRESHOLD,
                                      outlier_threshold=REL_DEV_THRESHOLD,
                                      pair_ratio_threshold=PAIR_RATIO_THRESHOLD,
                                      low_ratio_threshold=LOW_RATIO_THRESHOLD,
                                      high_pair_diff_threshold=HIGH_PAIR_DIFF_THRESHOLD,
                                      ge10_threshold=10.0):
    """
    Aggregate 1-4 direction-level thickness estimates into one crater-level value.

    Revised rule: sequential low-tail filtering.

    Rationale
    ---------
    The previous local-consensus rule required two conditions at the same time:
        low_ratio <= 0.477
        high_pair_diff <= 0.569

    This was too conservative for cases such as [79.5, 29.7, 0.7]. The smallest
    value is clearly a low-tail estimate, but the two remaining values are not
    close enough to satisfy high_pair_diff. For crater thickness estimates,
    directional thickness can vary laterally, so the two higher values do not
    have to form a tight pair before a clearly low value is removed.

    Data-driven thresholds
    ----------------------
    pair_ratio_threshold = 0.496
        Derived from Otsu automatic separation of min/max ratios among two-direction
        craters in Thickness.csv.

    low_ratio_threshold = 0.477
        Derived from Otsu automatic separation of low_ratio among multi-direction
        craters in Thickness.csv.

    Rules
    -----
    1) n = 1:
       keep the only valid direction.

    2) n = 2:
       pair_ratio = min(T1,T2) / max(T1,T2).
       If pair_ratio <= 0.496, keep only the larger value.
       Otherwise, average the two values.

    3) n >= 3:
       Compute:
           low_ratio = min_value / median(other directions)

       If low_ratio <= 0.477, remove the minimum value and repeat the check on
       the remaining directions. This allows multiple clearly low directions to
       be removed one after another.

       After low-tail filtering:
         - if two values remain, apply the same pair_ratio rule again;
         - if three or more values remain and no more low-tail value is detected,
           average all remaining values unless the fallback IQR/rel_dev rule is triggered.

    Important
    ---------
    This rule only removes low-tail direction values. It does not remove high
    direction values. In the fallback rule, if the most deviant value is the
    maximum, all values are still kept and averaged.

    Returns
    -------
    final_thickness, used_mask, flag
    """
    vals = np.asarray(values, dtype=float)
    finite = np.isfinite(vals)
    vals_valid = vals[finite]

    used_mask = np.zeros(vals.shape, dtype=bool)
    if vals_valid.size == 0:
        return np.nan, used_mask, "none"

    current_vals = vals_valid.copy()
    current_positions = np.where(finite)[0].copy()
    removed_low_count = 0

    def _rel_spread(arr):
        arr = np.asarray(arr, dtype=float)
        arr = arr[np.isfinite(arr)]
        if arr.size == 0:
            return np.inf
        med = float(np.nanmedian(arr))
        if not np.isfinite(med) or abs(med) < 1e-12:
            return 0.0 if float(np.nanmax(arr) - np.nanmin(arr)) == 0 else np.inf
        return float((np.nanmax(arr) - np.nanmin(arr)) / abs(med))

    def _use_current(flag_name):
        used_mask[current_positions] = True
        return float(np.nanmean(current_vals)), used_mask, flag_name

    while True:
        n = current_vals.size

        # Rule 1: one direction only.
        if n == 1:
            used_mask[current_positions[0]] = True
            if removed_low_count > 0:
                return float(current_vals[0]), used_mask, "rm_low_to_one"
            return float(current_vals[0]), used_mask, "one"

        # Rule 2: two directions. Apply this both for original n=2 and after
        # removing one or more low-tail values from n>=3.
        if n == 2:
            min_val = float(np.nanmin(current_vals))
            max_val = float(np.nanmax(current_vals))
            pair_ratio = min_val / max_val if max_val > 0 else 1.0

            if pair_ratio <= float(pair_ratio_threshold):
                max_pos_in_current = int(np.nanargmax(current_vals))
                used_mask[current_positions[max_pos_in_current]] = True
                if removed_low_count > 0:
                    return float(current_vals[max_pos_in_current]), used_mask, "rm_low_two_keepmax"
                return float(current_vals[max_pos_in_current]), used_mask, "two_keepmax"

            if removed_low_count > 0:
                return _use_current("rm_low_then_two_avg")
            return _use_current("two_avg")

        # Rule 3A: n >= 3. Remove clear low-tail values sequentially.
        min_pos = int(np.nanargmin(current_vals))
        min_val = float(current_vals[min_pos])
        other_vals = np.delete(current_vals, min_pos)
        med_other = float(np.nanmedian(other_vals))

        if np.isfinite(med_other) and abs(med_other) >= 1e-12:
            low_ratio = min_val / abs(med_other)
        else:
            low_ratio = np.inf

        if np.isfinite(low_ratio) and low_ratio <= float(low_ratio_threshold):
            current_vals = np.delete(current_vals, min_pos)
            current_positions = np.delete(current_positions, min_pos)
            removed_low_count += 1
            continue

        # Rule 3B: fallback. If directions are not strongly scattered by the
        # global relative_spread criterion, keep all remaining values.
        if _rel_spread(current_vals) <= float(spread_threshold):
            if removed_low_count > 0:
                return _use_current("rm_low_then_avg")
            return _use_current("avg")

        # Rule 3C: previous leave-one rel_dev fallback for extreme cases.
        rel_dev = np.full(current_vals.shape, np.nan, dtype=float)
        for i in range(current_vals.size):
            others = np.delete(current_vals, i)
            med_other = float(np.nanmedian(others))
            if np.isfinite(med_other) and abs(med_other) >= 1e-12:
                rel_dev[i] = abs(current_vals[i] - med_other) / abs(med_other)

        finite_dev = np.isfinite(rel_dev)
        if not np.any(finite_dev):
            if removed_low_count > 0:
                return _use_current("rm_low_then_avg_nodev")
            return _use_current("avg_nodev")

        worst_pos = int(np.nanargmax(rel_dev))
        worst_dev = float(rel_dev[worst_pos])

        if worst_dev <= float(outlier_threshold):
            if removed_low_count > 0:
                return _use_current("rm_low_then_avg_noout")
            return _use_current("avg_noout")

        worst_val = float(current_vals[worst_pos])
        min_val = float(np.nanmin(current_vals))
        max_val = float(np.nanmax(current_vals))
        tol = 1e-12

        if abs(worst_val - min_val) <= tol:
            current_vals = np.delete(current_vals, worst_pos)
            current_positions = np.delete(current_positions, worst_pos)
            removed_low_count += 1
            continue

        if abs(worst_val - max_val) <= tol:
            if removed_low_count > 0:
                return _use_current("rm_low_then_max_avg")
            return _use_current("max_avg")

        if removed_low_count > 0:
            return _use_current("rm_low_then_mid_avg")
        return _use_current("mid_avg")

def write_crater_summary_shp(direction_df: pd.DataFrame, out_shp: Path, cf_src):
    """
    Write one crater-level shapefile with a compact but useful attribute table.

    Existing direction-level shapefiles are not modified:
      - all_basalt_points.shp
      - basalt_thickness_points.shp

    New output:
      - basalt_thickness_crater_summary.shp

    Fields:
      name       crater name
      final_thk  robust crater-level thickness
      row_right  row-right direction thickness, if available
      col_right  col-right direction thickness, if available
      row_left   row-left direction thickness, if available
      col_left   col-left direction thickness, if available
      n_used     number of directions used to calculate final_thk
      flag       aggregation rule
    """
    if not HAS_GPD:
        print("geopandas/shapely unavailable; skip crater summary shapefile output.")
        return

    if direction_df is None or direction_df.empty:
        print(f"No direction records for crater summary shapefile output: {out_shp}")
        return

    df = direction_df.copy()
    if "h3_h3t_pass20" in df.columns:
        df = df[df["h3_h3t_pass20"].astype(bool)].copy()
    df["_thk"] = pd.to_numeric(df.get("thickness_or_depth", np.nan), errors="coerce")
    df = df[np.isfinite(df["_thk"])].copy()

    if df.empty:
        print(f"No valid thickness records for crater summary shapefile output: {out_shp}")
        return

    rows_out = []
    geoms = []
    direction_order = ["row_right", "col_right", "row_left", "col_left"]

    for name, sub in df.groupby("name", sort=False):
        # Direction fields are left blank if that direction is absent or invalid.
        dir_values = {k: np.nan for k in direction_order}
        dir_rows = {k: [] for k in direction_order}

        for idx, r in sub.iterrows():
            dname = direction_field_name(r.get("profile_type", ""), r.get("side", ""))
            if dname is None:
                continue
            thk = safe_float(r.get("_thk", np.nan))
            if not np.isfinite(thk):
                continue
            dir_rows[dname].append((idx, thk))

        # If duplicate records appear in any direction, average within that direction.
        for dname, items in dir_rows.items():
            if items:
                dir_values[dname] = float(np.nanmean([v for _, v in items]))

        vals = np.array([dir_values[d] for d in direction_order], dtype=float)
        final_thk, used_mask, flag = aggregate_crater_thickness_values(vals)
        if not np.isfinite(final_thk):
            continue

        # Geometry: use crater center when available. If not, use mean peak position
        # from the valid direction records.
        cr = pd.to_numeric(sub.get("center_row", np.nan), errors="coerce")
        cc = pd.to_numeric(sub.get("center_col", np.nan), errors="coerce")
        valid_center = np.isfinite(cr) & np.isfinite(cc)
        if np.any(valid_center):
            rr = int(round(float(cr[valid_center].iloc[0])))
            col = int(round(float(cc[valid_center].iloc[0])))
        else:
            pr = pd.to_numeric(sub.get("peak_row", np.nan), errors="coerce")
            pc = pd.to_numeric(sub.get("peak_col", np.nan), errors="coerce")
            valid_peak = np.isfinite(pr) & np.isfinite(pc)
            if not np.any(valid_peak):
                continue
            rr = int(round(float(np.nanmean(pr[valid_peak]))))
            col = int(round(float(np.nanmean(pc[valid_peak]))))

        if rr < 0 or rr >= cf_src.height or col < 0 or col >= cf_src.width:
            continue

        x, y = cf_src.xy(rr, col)
        rows_out.append({
            "name": str(name)[:80],
            "final_thk": float(final_thk),
            "row_right": safe_float(dir_values["row_right"]),
            "col_right": safe_float(dir_values["col_right"]),
            "row_left": safe_float(dir_values["row_left"]),
            "col_left": safe_float(dir_values["col_left"]),
            "n_used": int(np.sum(used_mask)),
            "flag": str(flag)[:12],
        })
        geoms.append(Point(x, y))

    if not rows_out:
        print(f"No crater summary records for shapefile output: {out_shp}")
        return

    gdf = gpd.GeoDataFrame(rows_out, geometry=geoms, crs=cf_src.crs)
    out_shp.parent.mkdir(parents=True, exist_ok=True)
    gdf.to_file(out_shp, driver="ESRI Shapefile", encoding="utf-8")
    print(f"Crater summary SHP saved: {out_shp}")


def filter_oldmethod_no_h3t_unpenetrated(df: pd.DataFrame) -> Tuple[pd.DataFrame, int]:
    """
    Build the old-method comparison dataset.

    The current main workflow may set thickness_or_depth = h3t for
    unpenetrated basalt profiles, with:
        thickness_source == "h3t_for_unpenetrated_basalt"

    For the extra old-method crater-summary shapefile, these records are
    removed before crater-level aggregation. This does not change the original
    three shapefile outputs.

    Returns
    -------
    filtered_df, removed_count
    """
    if df is None or df.empty:
        return df.copy(), 0

    out = df.copy()
    if "thickness_source" in out.columns:
        source = out["thickness_source"].astype(str).str.lower().str.strip()
        exclude = source.eq(OLDMETHOD_EXCLUDED_THICKNESS_SOURCE.lower())
    else:
        # Fallback for old CSVs without thickness_source.
        mode = out.get("thickness_mode", pd.Series("", index=out.index)).astype(str).str.lower()
        status = out.get("calculation_status", pd.Series("", index=out.index)).astype(str).str.lower()
        unpen = out.get("unpenetrated_flag", pd.Series(False, index=out.index)).apply(lambda v: safe_bool(v, False))
        exclude = (unpen.astype(bool) | mode.str.contains("unpenetrated") | status.str.contains("unpenetrated"))

    removed_count = int(exclude.sum())
    return out.loc[~exclude].copy(), removed_count

