"""
CalculateBasaltThickness.py

Purpose
-------
Use the h1/h2/h3/h3t results from CalculateH123.py step1 and ExtendCalculateH123.py step2
to calculate CE5-area basalt thickness or burial depth from DEM + CF rasters.

Main updates relative to the old CalculateUnitPixel.py
------------------------------------------------------
1. Basalt is defined as CF > 8.2, not CF < 8.2.
2. Rim type is judged only by the exact CF value at peak_row/peak_col, not by a local median window.
3. Filled crater filtering is NOT recalculated here. This script only reads
   profile_filled_flag / crater_filled_flag from the H123 CSV generated by
   CalculateH123.py and ExtendCalculateH123.py.
4. Unpenetrated basalt case is added:
   if both rims are basalt and all valid pixels between the two rims are basalt, the crater/profile
   is marked as basalt_only_unpenetrated; in the original three outputs, H3T is used as the direction-level thickness.
5. An extra old-method crater-summary shapefile is written after excluding H3T-derived unpenetrated basalt directions,
   so it can be used as a cleaner interpolation input.
6. The script writes annotated CSV outputs and point/crater shapefiles.

Expected inputs
---------------
- DEM raster: Database/CE5/CE5_dem.tif
- CF raster : Database/CE5/CE5_CF.tif
- Step1 CSV : Database/CE5/yolo/chickin/step1/all_yolo_h123.csv
- Step2 CSV : Database/CE5/yolo/chickin/step2/all_yolo_h123.csv

Example
-------
python scripts/CalculateBasaltThickness.py ^
  --dem Database/CE5/CE5_dem.tif ^
  --cf Database/CE5/CE5_CF.tif ^
  --step1-csv Database/CE5/yolo/chickin/step1/all_yolo_h123.csv ^
  --step2-csv Database/CE5/yolo/chickin/step2/all_yolo_h123.csv ^
  --out Database/CE5/yolo/chickin/basalt_thickness
"""

